package openwrt

import (
	"bytes"
	"fmt"
	"strings"
	"time"

	"github.com/denogio/familywarden/core/internal/platform"
)

// renderNetworkIntent translates the core's decision into an fw4 fragment.
// LAN interface discovery stays native; the marker is substituted by the
// shell immediately before nft validation. Neither UCI nor pact/RAM state is
// consulted here. Schedules and ticket deadlines remain kernel-evaluated.
func renderNetworkIntent(i platform.NetworkIntent, now time.Time) ([]byte, error) {
	if i.Format != platform.NetworkIntentFormat {
		return nil, fmt.Errorf("incompatible network intent")
	}
	var b bytes.Buffer
	emit := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	emit("# %s", platform.NetworkIntentFormat)
	emit("# intent-id %s", i.ID)
	emit("# Generated by FamilyWarden — do not edit")
	emit("set familywarden_ticket {")
	emit("    type ether_addr")
	emit("    flags timeout")
	elements := []string{}
	for _, t := range i.Tickets {
		if rem := t.Expires - now.Unix(); rem > 0 {
			elements = append(elements, fmt.Sprintf("%s timeout %ds", t.Mac, rem))
		}
	}
	if len(elements) > 0 {
		emit("    elements = { %s }", strings.Join(elements, ", "))
	}
	emit("}")
	for _, input := range []bool{true, false} {
		chain, hook, ticketMatch := "forward", "forward", ""
		if input {
			chain, hook, ticketMatch = "input", "input", "tcp dport 0-65535 "
		}
		emit("chain familywarden_%s {", chain)
		emit("    type filter hook %s priority 1; policy accept;", hook)
		tag := ""
		if input {
			tag = ":input"
		}
		emit("    ether saddr @familywarden_ticket %scounter accept comment \"familywarden:ticket%s\"", ticketMatch, tag)
		rules := i.Forward
		if input {
			rules = i.Router
		}
		for _, r := range rules {
			if r.Action != "accept" && r.Action != "drop" {
				return nil, fmt.Errorf("invalid network action")
			}
			match := ticketMatch
			if input && r.Recovery {
				match = "tcp dport != 7700 "
			}
			for _, mac := range r.Devices {
				comment := "familywarden:" + r.Profile + ":" + r.Reason + tag
				if len(r.Windows) > 0 {
					for _, w := range r.Windows {
						if err := renderNetworkWindow(&b, w, "ether saddr "+mac+" ", match, comment); err != nil {
							return nil, err
						}
					}
				} else {
					emit("    ether saddr %s %scounter %s comment %q", mac, match, r.Action, comment)
				}
			}
		}
		if !input && i.Enabled && i.DefaultPolicy == "block" {
			src := ""
			if len(i.AssignedMACs) > 0 {
				src = "ether saddr != { " + strings.Join(i.AssignedMACs, ", ") + " } "
			}
			emit("    iifname { @FAMILYWARDEN_LAN@ } %scounter drop comment \"familywarden:default:block\"", src)
		}
		emit("}")
	}
	emit("chain familywarden_lockdown {")
	emit("    type filter hook input priority 2; policy accept;")
	if c := i.Captain; c != nil {
		emit("    iifname \"lo\" accept")
		emit("    ct state established,related accept")
		emit("    tcp dport { 53, 7700 } accept")
		if c.PactType == "ongoing" {
			if err := renderNetworkWindow(&b, platform.Window{Days: []string{c.WindowDay}, Start: c.WindowStart, Stop: c.WindowStop}, "", "", "familywarden:ulysses:window"); err != nil {
				return nil, err
			}
		}
		for _, w := range c.Windows {
			if err := renderNetworkWindow(&b, w, "", "", "familywarden:"+c.ID+":sched-allow:lockdown"); err != nil {
				return nil, err
			}
		}
		until := ""
		if c.PactType == "until" {
			until = fmt.Sprintf("meta time < %d ", c.Until)
		}
		emit("    meta l4proto tcp %scounter drop comment \"familywarden:ulysses:lockdown\"", until)
	}
	emit("}")
	return b.Bytes(), nil
}

// nft cannot represent 24:00; the day selector supplies that exclusive bound.
func renderNetworkWindow(b *bytes.Buffer, w platform.Window, src, match, comment string) error {
	days, shifted := []string{}, []string{}
	for _, d := range w.Days {
		n := -1
		for j, name := range []string{"sun", "mon", "tue", "wed", "thu", "fri", "sat"} {
			if name == d {
				n = j
				break
			}
		}
		if n < 0 {
			return fmt.Errorf("invalid network window day %q", d)
		}
		days = append(days, fmt.Sprint(n))
		shifted = append(shifted, fmt.Sprint((n+1)%7))
	}
	if len(days) == 0 {
		return fmt.Errorf("empty network window days")
	}
	emit := func(clock string, days []string) {
		fmt.Fprintf(b, "    %s%smeta day { %s } %scounter accept comment %q\n", src, clock, strings.Join(days, ", "), match, comment)
	}
	switch {
	case w.Start < w.Stop:
		end := ""
		if w.Stop != "24:00" {
			end = "meta hour < " + w.Stop + " "
		}
		emit("meta hour >= "+w.Start+" "+end, days)
	case w.Start > w.Stop:
		if w.Start != "24:00" {
			emit("meta hour >= "+w.Start+" ", days)
		}
		if w.Stop != "00:00" {
			emit("meta hour < "+w.Stop+" ", shifted)
		}
	default:
		emit("", days)
	}
	return nil
}
